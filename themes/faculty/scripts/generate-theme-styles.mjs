// Generates src/theme-styles.generated.ts by concatenating assets/css/*.css
// — mirrors generate-svelte-sources.mjs's "compile at authoring time, raw
// text embedded as a JS string" approach, just for CSS instead of Svelte
// markup. Kept in explicit cascade order (not alphabetical) so specificity
// ties resolve the same way the previous single-file <style> block did.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const cssDir = join(scriptDir, '..', 'assets', 'css');
const outFile = join(scriptDir, '..', 'src', 'theme-styles.generated.ts');

const ORDER = ['base', 'header', 'navigation', 'hero', 'breadcrumb', 'sections', 'article', 'footer'];

const chunks = ORDER.map((name) => {
	const content = readFileSync(join(cssDir, `${name}.css`), 'utf-8').trimEnd();
	return `/* === ${name}.css === */\n${content}`;
});

const banner =
	'// AUTO-GENERATED by scripts/generate-theme-styles.mjs — do not edit directly.\n' +
	'// Edit the .css files in assets/css/ instead, then re-run `pnpm build`.\n\n';

writeFileSync(outFile, `${banner}export const ThemeStylesSource = ${JSON.stringify(chunks.join('\n\n'))};\n`, 'utf-8');
console.log(`Generated ${outFile} from ${ORDER.length} .css file(s).`);
