// Generates src/svelte-sources.generated.ts from src/layouts/*.svelte and
// src/blocks/*.svelte.
//
// Why this exists: tsup has *built-in* Svelte support (an unconditional
// esbuild `onLoad` plugin for `.svelte` files, see tsup/dist/index.js's
// `sveltePlugin`) that compiles for the CLIENT runtime with no way to
// disable it or make it emit SSR output instead — it wins over any
// `esbuildOptions().loader` override, since esbuild plugins intercept a
// file before the loader map is ever consulted. That's the wrong target:
// this theme's `.svelte` files are meant to be compiled at *site-build*
// time by apps/backend's SvelteSiteRenderer (`generate: 'server'`), not at
// theme-package-build time for a browser bundle.
//
// So real `.svelte` files stay on disk for authoring (full editor
// support), but never get `import`ed directly — this script reads them as
// plain text and writes out a `.ts` file exporting each as a string
// constant, which tsup then bundles as an ordinary string (no `.svelte`
// extension in sight, so its built-in plugin never sees them).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const srcDir = join(scriptDir, '..', 'src');
const outFile = join(srcDir, 'svelte-sources.generated.ts');

// Block components are prefixed so they can share a filename with a layout
// without colliding (`Hero.svelte` in both would otherwise emit the same
// export name twice, which only fails at build time).
const SOURCE_DIRS = [
  { dir: 'layouts', suffix: 'Source', prefix: '' },
  { dir: 'blocks', suffix: 'Source', prefix: 'Block' },
];

const exports = [];
let fileCount = 0;

for (const { dir, suffix, prefix } of SOURCE_DIRS) {
  const absolute = join(srcDir, dir);
  if (!existsSync(absolute)) continue;

  const files = readdirSync(absolute)
    .filter((file) => file.endsWith('.svelte'))
    .sort();

  for (const file of files) {
    const exportName = `${prefix}${basename(file, '.svelte')}${suffix}`;
    const content = readFileSync(join(absolute, file), 'utf-8');
    exports.push(`export const ${exportName} = ${JSON.stringify(content)};`);
    fileCount += 1;
  }
}

const banner =
  '// AUTO-GENERATED by scripts/generate-svelte-sources.mjs — do not edit directly.\n' +
  '// Edit the .svelte files in src/layouts/ and src/blocks/ instead, then re-run `pnpm build`.\n\n';

writeFileSync(outFile, banner + exports.join('\n\n') + '\n', 'utf-8');
console.log(`Generated ${outFile} from ${fileCount} .svelte file(s).`);
