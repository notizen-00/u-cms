// Generates src/svelte-sources.generated.ts from src/layouts/*.svelte.
//
// Why this exists: tsup has *built-in* Svelte support (an unconditional
// esbuild `onLoad` plugin for `.svelte` files, see tsup/dist/index.js's
// `sveltePlugin`) that compiles for the CLIENT runtime with no way to
// disable it or make it emit SSR output instead — it wins over any
// `esbuildOptions().loader` override, since esbuild plugins intercept a
// file before the loader map is ever consulted. That's the wrong target:
// this theme's `.svelte` files are meant to be compiled at *site-build*
// time by apps/backend's SvelteSiteRenderer (`generate: 'server'`), not at
// theme-package-build time for a browser bundle.
//
// So real `.svelte` files stay on disk for authoring (full editor
// support), but never get `import`ed directly — this script reads them as
// plain text and writes out a `.ts` file exporting each as a string
// constant, which tsup then bundles as an ordinary string (no `.svelte`
// extension in sight, so its built-in plugin never sees them).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const layoutsDir = join(scriptDir, '..', 'src', 'layouts');
const outFile = join(scriptDir, '..', 'src', 'svelte-sources.generated.ts');

const files = readdirSync(layoutsDir)
  .filter((file) => file.endsWith('.svelte'))
  .sort();

const exports = files.map((file) => {
  const exportName = `${basename(file, '.svelte')}Source`;
  const content = readFileSync(join(layoutsDir, file), 'utf-8');
  return `export const ${exportName} = ${JSON.stringify(content)};`;
});

const banner =
  '// AUTO-GENERATED by scripts/generate-svelte-sources.mjs — do not edit directly.\n' +
  '// Edit the .svelte files in src/layouts/ instead, then re-run `pnpm build`.\n\n';

writeFileSync(outFile, banner + exports.join('\n\n') + '\n', 'utf-8');
console.log(`Generated ${outFile} from ${files.length} .svelte file(s).`);
